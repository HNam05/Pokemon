"""Compile the generated forest artwork into a shared 4-bit RGB565 scene."""
import argparse
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def generate(check=False):
    source = Image.open(ROOT / 'assets/backgrounds/forest-source.png').convert('RGB')
    small = source.resize((240, 178), Image.Resampling.NEAREST)
    indexed = small.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    palette = indexed.getpalette()[:48]
    pixels = [indexed.getpixel((x,y)) for y in range(178) for x in range(240)]
    packed = [(pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2)]
    def rgb565(r, g, b):
        return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    day = [rgb565(*palette[i:i+3]) for i in range(0, 48, 3)]
    # A second palette shares every pixel with the daytime scene.
    night = [rgb565(r*42//100, g*52//100, min(255, b*65//100+22))
             for r, g, b in zip(palette[0::3], palette[1::3], palette[2::3])]
    output = '// Generated by scripts/import_background.py; see assets/backgrounds/README.md.\n'
    for name, values, kind in [('forest_pixels', packed, 'uint8_t'),
                               ('forest_day', day, 'uint16_t'), ('forest_night', night, 'uint16_t')]:
        output += f'constexpr std::{kind} {name}[] = {{' + ','.join(map(str, values)) + '};\n'
    target = ROOT / 'src/forest_scene.inc'
    if check:
        if target.read_text(encoding='utf-8') != output:
            raise ValueError('Forest data differs; regenerate explicitly')
    else:
        target.write_text(output, encoding='utf-8')
        indexed.save(ROOT / 'assets/backgrounds/forest-240x178.png')
    print(f'Forest: {len(packed)+64} bytes including day/night palettes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
