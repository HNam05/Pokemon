"""Offline deterministic roster compiler. Pillow is needed only for asset work."""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]


def generate(check=False):
    roster=json.loads((ROOT/'assets/roster.json').read_text(encoding='utf-8'))
    names={}
    for row in (ROOT/'assets/vendor/spritecollab/credit_names.txt').read_text(encoding='utf-8').splitlines():
        fields=row.split('\t')
        if len(fields)>=2:names[fields[1]]=fields[0] or fields[1]
    lines=['// Generated by scripts/import_sprites.py. See assets/ROSTER.md for credits and terms.']
    metadata=[];records=[];total_pixels=0;total_frames=0;total_unique=0
    for entry in sorted(roster['entries'],key=lambda e:e['id']):
        source=ROOT/'assets/vendor/spritecollab'/entry['directory']; prefix=f"set_{entry['id']}"
        for name,digest in entry['files'].items():
            if hashlib.sha256((source/name).read_bytes()).hexdigest()!=digest:raise ValueError(f'Changed source {source/name}')
        anims={a.findtext('Name'):a for a in ET.parse(source/'AnimData.xml').findall('./Anims/Anim')}
        palette=[0];raw_clips=[]
        for action in entry['actions']:
            name=action['source']; node=anims[name]
            w,h=int(node.findtext('FrameWidth')),int(node.findtext('FrameHeight'))
            durations=[max(70,int(d.text)*1000//30) for d in node.findall('./Durations/Duration')]
            sheet=Image.open(source/f'{name}-Anim.png').convert('RGBA')
            if sheet.width!=w*len(durations) or sheet.height%h:raise ValueError(f'Bad geometry {source}/{name}')
            frames=[]
            for i,duration in enumerate(durations):
                cell=sheet.crop((i*w,0,(i+1)*w,h));box=cell.getbbox()
                if box is None:raise ValueError(f'Empty frame {source}/{name}/{i}')
                crop=cell.crop(box);pixels=[]
                if crop.width>255 or crop.height>255:raise ValueError('Frame exceeds supported pixel dimensions')
                for r,g,b,a in (crop.getpixel((x,y)) for y in range(crop.height) for x in range(crop.width)):
                    if a not in (0,255):raise ValueError('Partial alpha')
                    color=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
                    if a==0:pixels.append(0)
                    else:
                        if color not in palette[1:]:palette.append(color)
                        pixels.append(palette.index(color,1))
                frames.append((pixels,crop.width,crop.height,box[0]-w//2,box[1]-h//2,duration))
            raw_clips.append(frames)
        if len(palette)>255:raise ValueError('More than 254 visible RGB565 colors')
        bits=4 if len(palette)<=16 else 8
        blobs=[];unique={};clips=[]
        for frames in raw_clips:
            packed_frames=[]
            for pixels,w,h,x,y,d in frames:
                padded=pixels+[0] if len(pixels)%2 else pixels
                blob=bytes((padded[i]<<4)|padded[i+1] for i in range(0,len(padded),2)) if bits==4 else bytes(pixels)
                if blob not in unique:unique[blob]=len(blobs);blobs.append(blob)
                packed_frames.append((unique[blob],w,h,x,y,d))
            clips.append(packed_frames)
        lines.append(f'namespace {prefix} {{')
        lines.append('constexpr std::uint16_t palette[] = {'+','.join(map(str,palette))+'};')
        for i,blob in enumerate(blobs):lines.append(f'constexpr std::uint8_t pixels_{i}[] = {{'+','.join(map(str,blob))+'};')
        for i,frames in enumerate(clips):
            lines.append(f'constexpr SpriteFrame frames_{i}[] = {{')
            for blob,w,h,x,y,d in frames:lines.append(f'    {{{{pixels_{blob},palette,{w},{h},{len(palette)},{bits}}},{x},{y},{d}}},')
            lines.append('};')
        lines.append('constexpr Clip clips[] = {')
        lines += [f'    {{frames_{i},{len(frames)}}},' for i,frames in enumerate(clips)]
        lines += ['};','}']
        # Tuple: pixels,width,height,x,y,duration. Fit all poses at one integer scale.
        extent=max(max(abs(f[3]),abs(f[3]+f[1])) for clip in raw_clips for f in clip)
        min_y=min(f[4] for clip in raw_clips for f in clip);max_y=max(f[4]+f[2] for clip in raw_clips for f in clip)
        scale=max(1,min(4,144//max(1,max_y-min_y),88//max(1,extent)))
        anchor=52+(144-(max_y-min_y)*scale)//2-min_y*scale
        if entry['id']==1:scale,anchor=4,152
        # Enlarge the companion itself; presentation bounds contain extreme travel.
        largest_width=max(f[1] for clip in raw_clips for f in clip)
        largest_height=max(f[2] for clip in raw_clips for f in clip)
        scale=min(scale+1,168//largest_height,180//largest_width)
        if scale<1:raise ValueError(f'Set too large: {entry["path"]}')
        idle_bottom=max(f[4]+f[2] for f in raw_clips[0])
        anchor=190-idle_bottom*scale
        credit=', '.join(names.get(c,c) for c in entry['credits'])
        metadata.append(f'    {{static_cast<Species>({entry["id"]}),{json.dumps(entry["name"],ensure_ascii=False)},{json.dumps(entry["form"],ensure_ascii=False)},{json.dumps(credit,ensure_ascii=False)},{prefix}::clips,{scale},{anchor}}},')
        byte_count=sum(map(len,blobs))+len(palette)*2
        records.append({**entry,'unique_frames':len(blobs),'pixel_bytes':byte_count,'bits':bits,'artist_names':credit,'scale':scale,'anchor_y':anchor})
        total_pixels+=byte_count;total_frames+=sum(map(len,clips));total_unique+=len(blobs)
    lines+=['constexpr ImportedSet imported_sets[] = {',*metadata,'};',f'constexpr std::size_t imported_pixel_bytes = {total_pixels};','']
    stats={'sets':len(records),'pokemon':len({e['dex'] for e in records}),'frames':total_frames,'unique_frames':total_unique,'pixel_bytes':total_pixels,'entries':records}
    md=['# Importierter Pokémon-Katalog','',f'{len(records)} Sets, {stats["pokemon"]} Pokémon, {total_frames} Frames in neun Pflegeabläufen. Quellenstand: `{roster["revision"]}`.','',
        'Alle Künstler werden unten genannt. Lizenzkennungen sind in `vendor/spritecollab/LICENSE.<Kennung>.md` dokumentiert. Pokémon-Markenrechte bleiben unberührt. Die Quellen wurden beschnitten, in RGB565-Paletten gepackt und zeitlich angepasst. Ausschlüsse und Gründe stehen in `roster.json`.','',
        '| ID | Pokémon | Form | Frames / Bilder | Künstler | Bedingungen | Quelle |','|---|---|---|---|---|---|---|']
    for e in records:md.append(f'| {e["id"]} | {e["name"]} | {e["form"] or "Standard"} | {e["frames"]} / {e["unique_frames"]} | {e["artist_names"]} | {", ".join(e["licenses"])} | [SpriteCollab](https://github.com/PMDCollab/SpriteCollab/tree/{roster["revision"]}/sprite/{e["path"]}) |')
    outputs=[(ROOT/'src/roster_frames.inc','\n'.join(lines)),(ROOT/'assets/roster_compiled.json',json.dumps(stats,ensure_ascii=False,indent=2)+'\n'),(ROOT/'assets/ROSTER.md','\n'.join(md)+'\n')]
    for path,value in outputs:
        if check:
            if path.read_text(encoding='utf-8')!=value:raise ValueError(f'Generated output differs: {path}')
        else:path.write_text(value,encoding='utf-8')
    print(f'{len(records)} sets; {total_frames} frames; {total_unique} unique bitmaps; {total_pixels} pixel/palette bytes')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true')
    generate(parser.parse_args().check)
