"""Offline, reproducible SpriteCollab conversion. Requires Pillow only for asset work.

Keeps the front-facing row, trims transparent borders with registration offsets,
deduplicates frames, and packs exact RGB565 palette indices (two per byte).
Never quantizes artwork silently. Source files and hashes are checked in.
"""
import hashlib
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/vendor/spritecollab/eevee-alternate'
CLIPS = ['Idle', 'Walk', 'Hop', 'Pose', 'Sleep', 'Eat', 'Sit', 'Hurt', 'LookUp']


def generate(check=False):
    manifest = json.loads((SOURCE / 'manifest.json').read_text())
    for name, digest in manifest['files'].items():
        if hashlib.sha256((SOURCE / name).read_bytes()).hexdigest() != digest:
            raise ValueError(f'Source checksum mismatch: {name}')
    xml = ET.parse(SOURCE / 'AnimData.xml')
    palette = [0]
    unique, blobs, clips = {}, [], []
    for name in CLIPS:
        anim = next(a for a in xml.findall('./Anims/Anim') if a.findtext('Name') == name)
        width, height = int(anim.findtext('FrameWidth')), int(anim.findtext('FrameHeight'))
        durations = [max(70, int(d.text) * 1000 // 30) for d in anim.findall('./Durations/Duration')]
        sheet = Image.open(SOURCE / f'{name}-Anim.png').convert('RGBA')
        if sheet.width != width * len(durations) or sheet.height % height:
            raise ValueError(f'Invalid sheet geometry: {name}')
        frames = []
        for index, duration in enumerate(durations):
            cell = sheet.crop((index * width, 0, (index + 1) * width, height))
            box = cell.getbbox()
            if box is None:
                raise ValueError(f'Empty front frame: {name}/{index}')
            crop = cell.crop(box)
            pixels = []
            for r, g, b, a in (crop.getpixel((x,y)) for y in range(crop.height) for x in range(crop.width)):
                if a not in (0, 255):
                    raise ValueError('Partial alpha is unsupported')
                color = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
                if a == 0:
                    pixels.append(0)
                else:
                    if color not in palette[1:]:
                        palette.append(color)
                    pixels.append(palette.index(color, 1))
            if len(palette) > 16:
                raise ValueError('Palette exceeds 4-bit storage')
            if len(pixels) % 2:
                pixels.append(0)
            packed = bytes((pixels[i] << 4) | pixels[i+1] for i in range(0, len(pixels), 2))
            if packed not in unique:
                unique[packed] = len(blobs)
                blobs.append(packed)
            frames.append((unique[packed], crop.width, crop.height, box[0]-width//2, box[1]-height//2, duration))
        clips.append(frames)
    lines = ['// Generated by scripts/import_sprites.py. Do not edit.',
             '// Evoli Alternate: Emmuffin / SpriteCollab. CC BY-NC 4.0.',
             '// Cropped front-facing frames; palette RGB565 conversion. See assets/README.md.',
             'constexpr std::uint16_t imported_palette[] = {' + ','.join(map(str,palette)) + '};']
    for i, blob in enumerate(blobs):
        lines.append(f'constexpr std::uint8_t imported_pixels_{i}[] = {{' + ','.join(map(str,blob)) + '};')
    for i, frames in enumerate(clips):
        lines.append(f'constexpr SpriteFrame imported_clip_{i}[] = {{')
        for blob,w,h,x,y,duration in frames:
            lines.append(f'    {{{{imported_pixels_{blob},imported_palette,{w},{h},{len(palette)}}},{x},{y},{duration}}},')
        lines.append('};')
    lines.append('constexpr Clip imported_clips[] = {')
    lines += [f'    {{imported_clip_{i},{len(frames)}}},' for i,frames in enumerate(clips)]
    lines += ['};', 'constexpr std::size_t imported_pixel_bytes = ' + str(sum(map(len,blobs))+2*len(palette)) + ';', '']
    output = ROOT / 'src/eevee_frames.inc'
    text = '\n'.join(lines)
    if check:
        if output.read_text(encoding='utf-8') != text:
            raise ValueError('Generated C++ assets differ. Run the importer.')
    else:
        output.write_text(text, encoding='utf-8')
    print(f'{sum(map(len,clips))} frames, {len(blobs)} unique bitmaps, {sum(map(len,blobs))+2*len(palette)} pixel/palette bytes')


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    generate(parser.parse_args().check)
