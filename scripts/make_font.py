def rows(art):
    if len(art) > 9 or any(len(row) != 5 or set(row) - {'.', '#'} for row in art):
        raise ValueError(f'Glyph must be at most 9 rows of 5 pixels: {art}')
    values = [int(row.replace('#', '1').replace('.', '0'), 2) for row in art]
    return values + [0] * (9 - len(values))


def main():
    entries = sorted(GLYPHS.items(), key=lambda item: ord(item[0]))
    lines = ['// Generated by scripts/make_font.py from the project-authored 5x9 font. Do not edit.',
             'struct Glyph { std::uint16_t codepoint; std::uint8_t rows[9]; };',
             'constexpr Glyph glyphs[] = {']
    for char, art in entries:
        values = ','.join(f'0x{value:02x}' for value in rows(art))
        lines.append(f'    {{0x{ord(char):04x},{{{values}}}}},')
    lines.append('};')
    (ROOT / 'src' / 'font.inc').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(entries)} glyphs')


if __name__ == '__main__':
    main()
